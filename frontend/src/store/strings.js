/** اسم المنتج/المتجر بلغة الواجهة، والعودة للعربي إن لم يوجد اسم إنجليزي. */
export const localName = (obj, lang) => (lang === "en" && obj?.nameEn?.trim() ? obj.nameEn.trim() : obj?.name || "");
export const localDescription = (p, lang) => (lang === "en" && p?.descriptionEn?.trim() ? p.descriptionEn.trim() : p?.description || "");

export function formatMoney(amount, currency, lang) {
  const n = Number(amount || 0).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const label = STRINGS[lang].currency[currency] || currency;
  return `${n} ${label}`;
}

/** نص رسالة الطلب — دائماً بالعربية بأسماء الأصناف العربية وأكوادها: هي ما يقرؤه موظف المبيعات ويطابقه بالمخزون. */
export function buildOrderMessage({ storeName, rows, totals, currency, customer, orderNumber }) {
  const o = STRINGS.ar.order;
  const lines = rows.map((r, i) => o.line(i + 1, r, formatMoney(r.price * r.qty, currency, "ar")));
  return [
    o.title(storeName),
    ...(orderNumber ? [STRINGS.ar.orderNo(orderNumber)] : []),
    "",
    ...lines,
    "",
    ...(totals.discount ? [`${STRINGS.ar.discount}: ${formatMoney(totals.discount, currency, "ar")}`] : []),
    ...(totals.shippingFee ? [`${STRINGS.ar.shippingFee}: ${formatMoney(totals.shippingFee, currency, "ar")}`] : []),
    `${o.total}: ${formatMoney(totals.total, currency, "ar")}`,
    ...(totals.shipping ? [`${STRINGS.ar.shippingMethod}: ${totals.shipping}`] : []),
    ...(totals.payment ? [`${STRINGS.ar.payment}: ${totals.payment}`] : []),
    "",
    `${o.customer}: ${customer.name}`,
    `${o.mobile}: ${customer.mobile}`,
    `${o.city}: ${customer.city}`,
    ...(customer.notes ? [`${o.notes}: ${customer.notes}`] : []),
  ].join("\n");
}

