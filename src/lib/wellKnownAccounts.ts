/**
 * يتتبّع سلسلة الأسماء البديلة بالكامل (الاسم المطلوب أولاً، ثم بدائله، ثم بدائل بدائله...) عبر
 * استعلام واحد لقاعدة البيانات، ويُرجع أول اسم موجود فعلياً في شجرة الشركة حسب ترتيب الأولوية.
 * هذا يسمح بالتوافق مع أكثر من "جيل" من قوالب شجرة الحسابات (القالب الأصلي، إعادة بناء القالب
 * القياسي، وقوالب الأنشطة الخمسة المبنية على ملفات CSV) دون الحاجة لتفكيك كل سلسلة يدوياً.
 */
function collectCandidates(name: string): string[] {
  const seen = new Set<string>();
  const order: string[] = [];
  const queue = [name];
  while (queue.length) {
    const current = queue.shift()!;
    if (seen.has(current)) continue;
    seen.add(current);
    order.push(current);
    const next = STANDARD_ACCOUNT_ALIASES[current];
    if (next) queue.push(...(Array.isArray(next) ? next : [next]));
  }
  return order;
}

export async function getAccountIdByName(tenantId: string, companyId: string, name: string): Promise<string> {
  const candidates = collectCandidates(name);
  const accounts = await prisma.account.findMany({
    where: { tenantId, companyId, name: { in: candidates }, isPosting: true, isArchived: false, isActive: true },
  });
  for (const candidate of candidates) {
    const found = accounts.find((account) => account.name === candidate);
    if (found) return found.id;
  }
  throw badRequest(`الحساب المطلوب لترحيل هذه المعاملة غير موجود في شجرة الشركة: "${name}"`);
}
