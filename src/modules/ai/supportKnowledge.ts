/**
 * «الدعم الفني» في أثر الذكي: معرفة الاستخدام التي يجيب منها النموذج. خريطة القوائم مولَّدة من كود الواجهة نفسه
 * (scripts/build-support-menu.mjs ← supportMenu.generated.json)، واختبار supportKnowledge.test.ts يعيد توليدها ويقارن،
 * فلا تنحرف عن القوائم الفعلية. الإجابات العامة أدناه مكتوبة يدوياً من نصوص الواجهة الحالية — وأي شيء غير مذكور هنا
 * يُحال للدعم البشري بدل التخمين.
 */
export const SUPPORT_MENU = menu;

export function menuOutline(): string {
  const lines = [`- ${menu.dashboard}`];
  for (const g of menu.groups) lines.push(`- ${g.label}: ${g.tabs.map((t) => t.label).join(" ، ")}`);
  return lines.join("\n");
}

