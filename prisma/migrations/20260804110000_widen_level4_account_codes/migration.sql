-- المستوى الرابع (حسابات الترحيل) كان يُرقَّم برقم إضافي واحد فقط فوق كود الأب المكوّن من 3
-- أرقام (كود من 4 أرقام إجمالاً)، أي بحد أقصى 9 حسابات ترحيل تحت كل فرع مستوى ثالث — تبيّن عملياً
-- أنه ضيق جداً لشركات فيها عشرات العملاء/الموردين/الحسابات البنكية تحت فرع واحد. نوسّعه إلى 3
-- أرقام إضافية (كود من 6 أرقام إجمالاً)، أي حتى 999 حساب لكل فرع.
--
-- التحويل: كود الأب (3 أرقام) يبقى كما هو، والرقم الإضافي القديم (رقم واحد، من 1 إلى 9) يُصبح
-- مبطَّناً بأصفار من اليسار إلى 3 أرقام — فمثلاً "1121" تصبح "112001". هذا تحويل آمن 1-إلى-1 بلا أي
-- احتمال تصادم: كل الأكواد القديمة طولها 4 أحرف بالضبط وكل الأكواد الجديدة طولها 6 أحرف بالضبط،
-- فمساحة القيم الجديدة منفصلة تماماً عن القديمة حتى أثناء تنفيذ UPDATE نفسه.
--
-- معرّف الحساب (accountId) هو ما تُخزَّنه كل القيود/الفواتير/السطور فعلياً كمفتاح أجنبي — لا شيء في
-- الكود يعتمد على قيمة "code" كمفتاح عمل (كل عمليات البحث عن حساب معياري تتم بالاسم عبر
-- getAccountIdByName)، فهذا التحويل آمن على كل البيانات التاريخية.
UPDATE "accounts"
SET "code" = LEFT("code", 3) || LPAD(SUBSTRING("code" FROM 4), 3, '0')
WHERE "level" = 4 AND LENGTH("code") = 4;
